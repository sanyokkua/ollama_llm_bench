"""Shared, Qt-free domain vocabulary: enums, type aliases, constrained types, and records.

This module is the base of the Phase 1 dependency graph. It defines every closed
enumeration (`StrEnum`), every type alias, every reusable `msgspec.Meta`-constrained
type, and every cross-boundary `msgspec.Struct` record catalogued in
``docs/v3_specification/10_Domain_and_Data/02_DTOS_AND_ENUMS.md`` sections 2, 3, 5, 6,
and 7 — including the runtime-only run-log DTOs (``RunLogEvent``, ``RunLogEventKind``,
``RunLogVerbosity``, §7.7) — excluding the EventBus payload structs and their
locally-scoped enums (``InferenceProgressEvent``, ``JudgeModelExcludedEvent``,
``DriftWarning``, ``DriftSeverity``, ``DriftKind``), which are owned by STORY-003.

This module imports nothing project-internal: standard library and ``msgspec`` only.
"""

from enum import StrEnum
from typing import Annotated

import msgspec

# ---------------------------------------------------------------------------------
# 2. Type aliases (`02_DTOS_AND_ENUMS.md` §2)
# ---------------------------------------------------------------------------------

type RunId = int
"""Auto-incrementing primary key of a benchmark run; always > 0."""

type ResultId = int
"""Auto-incrementing primary key of a benchmark result; always > 0."""

type TaskId = str
"""Unique-within-run task identifier; non-empty."""

type ProviderId = str
"""INTERNAL provider identifier; a UUID4 textual representation, auto-generated by
``ProvidersStore`` on insert. Never user-entered and never displayed in the UI (DD-33)."""

type ModelName = str
"""Provider-defined model string; max 256 characters."""

type SettingKey = str
"""Dotted settings key, e.g. ``"benchmark.retry_count"``."""

type Iso8601Utc = str
"""ISO-8601 timestamp in UTC, e.g. ``"2026-05-22T14:53:09Z"``."""

# ---------------------------------------------------------------------------------
# 3. Reusable constrained types (`02_DTOS_AND_ENUMS.md` §3)
# ---------------------------------------------------------------------------------

ProviderIdStr = Annotated[
    str,
    msgspec.Meta(
        pattern=r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$",
        max_length=36,
    ),
]
"""Internal UUID4 identifier constraint; a constraint violation raises at construction."""

ModelNameStr = Annotated[str, msgspec.Meta(min_length=1, max_length=256)]
TaskIdStr = Annotated[str, msgspec.Meta(min_length=1, max_length=128)]
NonNegativeFloat = Annotated[float, msgspec.Meta(ge=0.0)]
PositiveFloat = Annotated[float, msgspec.Meta(gt=0.0)]
NonEmptyStr = Annotated[str, msgspec.Meta(min_length=1)]
CosineScore = Annotated[float, msgspec.Meta(ge=0.0, le=1.0)]
CosineThreshold = Annotated[float, msgspec.Meta(ge=0.0, le=1.0)]
RetryCount = Annotated[int, msgspec.Meta(ge=0, le=10)]
TimeoutSeconds = Annotated[int, msgspec.Meta(ge=1, le=3600)]
PositiveInt = Annotated[int, msgspec.Meta(ge=1)]
NonNegativeInt = Annotated[int, msgspec.Meta(ge=0)]
DurationMs = Annotated[int, msgspec.Meta(ge=0)]
RepeatCount = Annotated[int, msgspec.Meta(ge=1, le=50)]

